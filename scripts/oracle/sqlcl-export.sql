-- Exports what the load left in REF and APP the way SQL Developer does: DDL from DBMS_METADATA (keys in the table
-- DDL, foreign keys in their own files, `;` terminators, storage clauses) and rows as INSERT statements.
-- The object list follows the generator's schema (src/synth/schema.rs).
SET FEEDBACK OFF
SET LONG 1000000
SET LONGCHUNKSIZE 1000000
SET PAGESIZE 0
SET LINESIZE 32767
SET HEADING OFF
SET TRIMSPOOL ON
BEGIN
  DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM, 'SQLTERMINATOR', TRUE);
  DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM, 'PRETTY', TRUE);
  DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM, 'REF_CONSTRAINTS', FALSE);
END;
/

